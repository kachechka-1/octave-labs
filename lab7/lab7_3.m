% Лабораторна робота № 7. Циклічні обчислювальні процеси. Завдання 3. Варіант № 4
% Табулювання y = x^3 * ln(1 + x) на [1; 6], кількість і добуток y < 100
clc; clear;

a = 1;
b = 6;
h = 0.1 * (b - a);       % крок 0.5
kilk = 0;                % кількість y < 100
dob = 1;                 % добуток y < 100

fprintf('    x          y\n');
for x = a : h : b
    y = x^3 * log(1 + x);
    fprintf('%6.2f   %10.4f\n', x, y);
    if y < 100
        kilk = kilk + 1;
        dob = dob * y;
    end
end

fprintf('Кількість y < 100: %d\n', kilk);
fprintf('Добуток y < 100: %.4f\n', dob);
