% Лабораторна робота № 7. Циклічні обчислювальні процеси. Завдання 2. Варіант № 4
% Обчислити різницю між сумами елементів з непарними і парними номерами.
clc; clear;

% 1. Масив з умови завдання
A = [0.1; -27.3; 35.7; -71.4; 0; 12; -5; -7.3; 0.5; 14];

% 2. Суми елементів на непарних (1-й, 3-й, 5-й...) і парних (2-й, 4-й...) місцях
sum_odd = 0;
sum_even = 0;
for i = 1:length(A)
    if mod(i, 2) == 1          % непарний номер
        sum_odd = sum_odd + A(i);
    else                       % парний номер
        sum_even = sum_even + A(i);
    end
end

% 3. Різниця між сумою непарних і парних елементів
diff_result = sum_odd - sum_even;

% 4. Виведення результатів у консоль
fprintf('Сума елементів на непарних місцях: %.2f\n', sum_odd);
fprintf('Сума елементів на парних місцях: %.2f\n', sum_even);
fprintf('Різниця між ними: %.2f\n', diff_result);
