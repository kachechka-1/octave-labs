% Лабораторна робота № 7. Циклічні обчислювальні процеси. Завдання 1. Варіант № 4
% S = sum(i = 1..N) sum(j = 1..50) x / (i + j^2),  N = 20, x = 0.54
clc; clear;

% Введення початкових даних
n = inputdlg({'N =', 'x =', 'S ='}, 'Задача 4', 1, {'20', '0.54', ''});
N = str2double(n(1,1));
x = str2double(n(2,1));

S = 0;
% Подвійний цикл
for i = 1:N
    for j = 1:50
        S = S + x / (i + j^2);
    end
end

% Виведення результату
N = num2str(N);
x = num2str(x);
S = num2str(S);
n = inputdlg({'N =', 'x =', 'S ='}, 'Задача 4', 1, {N, x, S});
