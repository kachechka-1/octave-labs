% Лабораторна робота № 6. Розгалужені обчислювальні процеси. Завдання 2. Варіант № 4
% Квадратне рівняння a*x^2 + b*x + c = 0. Обчислити:
%   y = a^2 - 9*b*c,  якщо D < 0
%   y = 4*x1,         якщо D = 0
%   y = x2*sin(x1),   якщо D > 0
clc; clear;

disp('ЛАБОРАТОРНА РОБОТА № 6. РОЗГАЛУЖЕНІ ПРОЦЕСИ. ЗАВДАННЯ 2. ВАРІАНТ № 4');

% Рядок 1 - дані варіанта 4; рядки 2, 3 - перевірка гілок D = 0 та D < 0
K = [7.2  5.3  -3.6;
     1    2     1;
     1    1     1];

for k = 1 : size(K, 1)
    a = K(k, 1);  b = K(k, 2);  c = K(k, 3);
    fprintf('\nНабір %d. Квадратне рівняння: %.3fx^2 + (%.3f)x + (%.3f) = 0\n', k, a, b, c);

    % Обчислення дискримінанта
    D = b^2 - 4*a*c;
    fprintf('D = %.3f\n', D);

    % Вибір формули: switch true
    switch true
        case D < 0
            y = a^2 - 9*b*c;
            fprintf('Корені відсутні (D < 0)\n');
            fprintf('y = a^2 - 9bc = %.3f\n', y);
        case abs(D) < 1e-9          % D = 0 бо воно його зберігає з округленям як 0.000000001 тому не просто d == 0
            x1 = -b / (2*a);
            y = 4 * x1;
            fprintf('Корінь: x1 = x2 = %.3f\n', x1);
            fprintf('y = 4*x1 = %.3f\n', y);
        otherwise                   % D > 0
            x1 = (-b - sqrt(D)) / (2*a);
            x2 = (-b + sqrt(D)) / (2*a);
            y = x2 * sin(x1);
            fprintf('Корені рівняння: x1 = %.3f, x2 = %.3f\n', x1, x2);
            fprintf('y = x2*sin(x1) = %.3f\n', y);
    end
end
