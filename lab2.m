clear;
clc;

% Виправлення подвійного виводу для diary в Windows
if exist('page_screen_output', 'builtin')
    page_screen_output(0);
end

diary lab2.txt;

disp('   ЛАБОРАТОРНА РОБОТА № 2. ВАРІАНТ № 4');

%% ЧАСТИНА 1. ОПЕРАЦІЇ З МАТРИЦЯМИ І МАСИВАМИ
disp(' ЧАСТИНА 1. ОПЕРАЦІЇ З МАТРИЦЯМИ І МАСИВАМИ ');

N = 4; % Номер варіанта
fprintf('Номер варіанта N = %d\n\n', N);

% 1. Вектор A1(7) рівновіддалених елементів на проміжку (-N, N)
A1 = linspace(-N, N, 7);
disp('1. Вектор A1 (linspace від -N до N, 7 елементів):');
disp(A1);

% 2. Вектор A2(7) на проміжку (-N, N) із кроком h = N/3
h = N / 3;
A2 = -N : h : N;
disp('2. Вектор A2 (від -N до N з кроком h = N/3):');
disp(A2);

% 3. Вектор A3(7) як сума A1 та A2
A3 = A1 + A2;
disp('3. Вектор A3 = A1 + A2:');
disp(A3);

% 4. Вектор A4(7): A4(i) = (cos(A1(i) - A2(i)))^2 + A3(i)^3
A4 = (cos(A1 - A2)).^2 + A3.^3;
disp('4. Вектор A4 = (cos(A1 - A2)).^2 + A3.^3:');
disp(A4);

% 5. Матриця A(4,7), рядками якої є вектори A1, A2, A3, A4
A_mat = [A1; A2; A3; A4];
disp('5. Матриця A (4x7):');
disp(A_mat);

% 6. Матриця B(7,7) з діагоналлю A1
B_mat = diag(A1);
disp('6. Матриця B (7x7) з діагоналлю A1:');
disp(B_mat);

% 7. Елементи матриці A, які належать проміжку (-N/2, N/2)
niz_bound = -N / 2;
verh_bound = N / 2;
fprintf('7. Пошук елементів у проміжку (%.1f, %.1f):\n', niz_bound, verh_bound);
idx = find(A_mat > niz_bound & A_mat < verh_bound);
vals = A_mat(idx);

disp('Значення знайдених елементів:');
disp(vals');

%% ЧАСТИНА 2. РОЗВ’ЯЗУВАННЯ СИСТЕМИ ЛІНІЙНИХ РІВНЯНЬ
disp('----------------------------------------------------------------');
disp('ЧАСТИНА 2 РОЗВ’ЯЗУВАННЯ СИСТЕМИ ЛІНІЙНИХ РІВНЯНЬ ');


% Матриця коефіцієнтів та вектор вільних членів
A_sys = [-4  9.3  7;
         14  7    9;
         14  4.1 -2];
B_sys = [21; 9; -6];

disp('Матриця коефіцієнтів A_sys:');
disp(A_sys);
disp('Вектор вільних членів B_sys:');
disp(B_sys);

% Розв'язання трьома способами
disp('Спосіб 1: x = A_sys^(-1) * B_sys:');
x_sol1 = A_sys^(-1) * B_sys;
disp(x_sol1);

disp('Спосіб 2: x = inv(A_sys) * B_sys:');
x_sol2 = inv(A_sys) * B_sys;
disp(x_sol2);

disp('Спосіб 3 (рекомендований): x = A_sys \ B_sys:');
x_sol3 = A_sys \ B_sys;
disp(x_sol3);

% Перевірка правильності розв'язку
disp('Перевірка: обчислення нев''язки A_sys * x:');
check_B = A_sys * x_sol3;
disp(check_B);
disp('Різниця (A_sys * x - B_sys):');
disp(check_B - B_sys);

diary off;
disp('Результати збережено у lab2.txt');
