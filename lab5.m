% Лабораторна робота № 5. Програми лінійної структури. Варіант № 4
% Задача: дано сторони a, b, c трикутника. Знайти площу трикутника
% за формулою Герона: S = sqrt(p(p-a)(p-b)(p-c)), де p - півпериметр.
clc; clear;

disp('ЛАБОРАТОРНА РОБОТА № 5. ПРОГРАМИ ЛІНІЙНОЇ СТРУКТУРИ. ВАРІАНТ № 4');

%% Спосіб 1. Введення/виведення у командному вікні (input, disp)
disp('--- Спосіб 1 (input / disp) ---');
a = input('Введіть сторону a = ');
b = input('Введіть сторону b = ');
c = input('Введіть сторону c = ');

p = (a + b + c) / 2;                      % півпериметр
S = sqrt(p * (p - a) * (p - b) * (p - c)); % формула Герона

disp(['Півпериметр p = ', num2str(p)]);
disp(['Площа трикутника S = ', num2str(S)]);

%% Спосіб 2. Діалогове вікно (inputdlg)
names = {'Сторона a =', 'Сторона b =', 'Сторона c =', ...
         'Півпериметр p =', 'Площа S ='};
n = inputdlg(names, 'Лабораторна № 5. Формула Герона', 1);

a = str2double(n{1});
b = str2double(n{2});
c = str2double(n{3});

p = (a + b + c) / 2;
S = sqrt(p * (p - a) * (p - b) * (p - c));

n = inputdlg(names, 'Лабораторна № 5. Формула Герона', 1, ...
    {num2str(a), num2str(b), num2str(c), num2str(p), num2str(S)});
